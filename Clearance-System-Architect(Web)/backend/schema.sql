BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (name IN ('student', 'admin'))
);

CREATE TABLE IF NOT EXISTS permissions (
    permission_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id SMALLINT NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    permission_id SMALLINT NOT NULL REFERENCES permissions(permission_id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS users (
    user_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username TEXT NOT NULL UNIQUE
        CHECK (username = lower(username))
        CHECK (username ~ '^[a-z0-9._-]{3,32}$'),
    password_hash TEXT NOT NULL,
    role_id SMALLINT NOT NULL REFERENCES roles(role_id),
    student_id TEXT UNIQUE,
    full_name TEXT NOT NULL CHECK (length(full_name) BETWEEN 1 AND 120),
    program TEXT,
    academic_year TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (student_id IS NOT NULL AND program IS NOT NULL AND academic_year IS NOT NULL)
        OR
        (student_id IS NULL AND program IS NULL AND academic_year IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS registration_invites (
    invite_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    token_hash CHAR(64) NOT NULL UNIQUE,
    student_id TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL CHECK (length(full_name) BETWEEN 1 AND 120),
    program TEXT NOT NULL,
    academic_year TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    claimed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS departments (
    department_id TEXT PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS clearance_requests (
    request_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    student_id UUID NOT NULL REFERENCES users(user_id),
    department_id TEXT NOT NULL REFERENCES departments(department_id),
    status TEXT NOT NULL CHECK (status IN ('pending', 'approved', 'rejected')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    note TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 1000),
    reviewed_by UUID REFERENCES users(user_id),
    reviewed_at TIMESTAMPTZ,
    admin_note TEXT NOT NULL DEFAULT '' CHECK (length(admin_note) <= 1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (student_id, department_id)
);

CREATE INDEX IF NOT EXISTS clearance_requests_status_idx
    ON clearance_requests (status, submitted_at DESC);
CREATE INDEX IF NOT EXISTS clearance_requests_student_idx
    ON clearance_requests (student_id, submitted_at DESC);

CREATE TABLE IF NOT EXISTS audit_logs (
    audit_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_user_id UUID NOT NULL REFERENCES users(user_id),
    target_student_id UUID NOT NULL REFERENCES users(user_id),
    department_id TEXT NOT NULL REFERENCES departments(department_id),
    action TEXT NOT NULL CHECK (action IN ('clearance_submitted', 'clearance_reviewed')),
    action_status TEXT NOT NULL CHECK (action_status IN ('pending', 'approved', 'rejected')),
    details TEXT NOT NULL DEFAULT '' CHECK (length(details) <= 1000),
    ip_address INET,
    user_agent TEXT CHECK (user_agent IS NULL OR length(user_agent) <= 512),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_logs_occurred_at_idx
    ON audit_logs (occurred_at DESC);
CREATE INDEX IF NOT EXISTS audit_logs_target_idx
    ON audit_logs (target_student_id, occurred_at DESC);

CREATE TABLE IF NOT EXISTS user_sessions (
    sid VARCHAR NOT NULL PRIMARY KEY,
    sess JSON NOT NULL,
    expire TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS user_sessions_expire_idx ON user_sessions (expire);

INSERT INTO roles (name) VALUES ('student'), ('admin')
ON CONFLICT (name) DO NOTHING;

INSERT INTO permissions (name) VALUES
    ('clearance:read:own'),
    ('clearance:submit:own'),
    ('clearance:read:any'),
    ('clearance:review:any'),
    ('audit:read')
ON CONFLICT (name) DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM roles r
JOIN permissions p ON
    (r.name = 'student' AND p.name IN ('clearance:read:own', 'clearance:submit:own'))
    OR
    (r.name = 'admin' AND p.name IN ('clearance:read:any', 'clearance:review:any', 'audit:read'))
ON CONFLICT DO NOTHING;

INSERT INTO departments (department_id, name) VALUES
    ('library', 'Library'),
    ('accounting', 'Accounting'),
    ('laboratory', 'Laboratory'),
    ('registrar', 'Registrar'),
    ('student-affairs', 'Student Affairs')
ON CONFLICT (department_id) DO NOTHING;

CREATE OR REPLACE FUNCTION prevent_audit_log_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Audit log records cannot be changed or deleted';
END;
$$;

DROP TRIGGER IF EXISTS audit_logs_immutable ON audit_logs;
CREATE TRIGGER audit_logs_immutable
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_log_mutation();
DROP TRIGGER IF EXISTS audit_logs_no_truncate ON audit_logs;
CREATE TRIGGER audit_logs_no_truncate
    BEFORE TRUNCATE ON audit_logs
    FOR EACH STATEMENT EXECUTE FUNCTION prevent_audit_log_mutation();

COMMIT;
